import { describe, expect, it } from 'vitest';
import { dative } from './defaults';

describe('дательный падеж названия предмета', () => {
  it.each([
    ['Математика', 'Математике'],
    ['История', 'Истории'],
    ['ИКТ', 'ИКТ'],
    ['Ин. язык', 'Ин. языку'],
    ['Каз/рус язык', 'Каз/рус языку'],
    ['Физкультура', 'Физкультуре'],
  ])('%s → %s', (a, b) => expect(dative(a)).toBe(b));
});
